// Dibuja el logo subido 2 px (queda en y=0..59) y una barra de carga
// debajo (y=61..63) que se llena en durationMs.
inline void showSplash(Adafruit_SSD1306 &disp, uint16_t durationMs = 2000) {
    const int16_t LOGO_Y = -2;   // las 2 primeras filas del bitmap estan vacias
    const int16_t BAR_X  = 14;
    const int16_t BAR_Y  = 61;
    const int16_t BAR_W  = 100;
    const int16_t BAR_H  = 3;
    const int     STEPS  = 50;

    for (int i = 0; i <= STEPS; i++) {
        disp.clearDisplay();
        disp.drawBitmap(0, LOGO_Y, splashLogo, 128, 64, SSD1306_WHITE);
        disp.drawRect(BAR_X, BAR_Y, BAR_W, BAR_H, SSD1306_WHITE);
        int16_t fillW = (int32_t)(BAR_W - 2) * i / STEPS;
        if (fillW > 0) disp.drawFastHLine(BAR_X + 1, BAR_Y + 1, fillW, SSD1306_WHITE);
        disp.display();
        delay(durationMs / STEPS);
    }
    disp.clearDisplay();
    disp.display();
}
